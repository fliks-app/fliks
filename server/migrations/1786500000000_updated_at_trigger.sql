-- Replaces TypeORM's @UpdateDateColumn; keeps an explicitly changed "updatedAt".
CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW."updatedAt" IS NOT DISTINCT FROM OLD."updatedAt" THEN
    NEW."updatedAt" = now();
  END IF;
  RETURN NEW;
END $$;

