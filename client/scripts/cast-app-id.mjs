// Writes the dev Cast app ID from ../.env.local (prod ID when unset; the env var wins, for the dev container) for the dev Angular builds and the iOS Debug build.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const PROD = '66BF4DAE';
const root = new URL('../../', import.meta.url);
const envFile = new URL('.env.local', root);
const line = existsSync(envFile)
  ? readFileSync(envFile, 'utf8').split('\n').find((l) => l.startsWith('FLIKS_CAST_APP_ID='))
  : undefined;
const id = process.env.FLIKS_CAST_APP_ID?.trim() || line?.slice('FLIKS_CAST_APP_ID='.length).trim().replace(/^(['"])(.*)\1$/, '$2') || PROD;

writeFileSync(
  new URL('client/src/environments/cast-app-id.generated.ts', root),
  `// Generated by scripts/cast-app-id.mjs from .env.local; do not edit.\nexport const CAST_APP_ID = '${id}';\n`,
);
writeFileSync(
  new URL('client/ios/App/App/Local.xcconfig', root),
  `FLIKS_CAST_APP_ID = ${id}\n`,
);
console.log(`cast app id: ${id}`);
