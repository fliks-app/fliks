const JOINERS = [' ', '.', '_', '-', ' - ', '/', '(', ')', '', ' ', '\t'];

/** Language and flag inference of stream titles: curated words, then seeded combinations. */
export function titleVectors() {
  const rng = mulberry32(7);
  const pick = <T>(a: T[]) => a[Math.floor(rng() * a.length)];
  const titles = new Set<string>(WORDS);
  for (let i = 0; i < 1500; i++) {
    const n = 1 + Math.floor(rng() * 3);
    let t = '';
    for (let k = 0; k < n; k++) t += (k ? pick(JOINERS) : '') + pick(WORDS);
    titles.add(t);
  }
  return [...titles].sort().map((title) => {
    const f = subtitleFlagsFromTitle(title);
    return {
      title,
      language: inferLanguageCodeFromTitle(title),
      forced: f.forced,
      hearingImpaired: f.hearingImpaired,
    };
  });
}

/** `formatFps` of the host (private there): the same expression on awkward doubles. */
export function fpsVectors() {
  const rng = mulberry32(11);
  const values = new Set<number>([
    24,
    25,
    30,
    50,
    60,
    23.976023976,
    29.97002997,
    59.94005994,
    47.952,
    119.88,
    0.0625,
    0.1875,
    9.9995,
    1.0005,
    2.5,
    24.0005,
    24.9995,
    100.0625,
    12.3125,
    1e-4,
    479.99999,
    1.0004999999999999,
    0.0005,
    0.0015,
    0.0025,
    1 / 3,
    2 / 3,
    500 / 21,
    24000 / 1001,
    30000 / 1001,
    60000 / 1001,
  ]);
  for (let i = 0; i < 400; i++) values.add(1 + rng() * 480);
  // Exact ties: k / 2048 has a short exact binary expansion.
  for (let k = 1; k < 60; k++) values.add(k / 2048 + Math.floor(rng() * 100));
  return [...values].map((fps) => ({
    fps,
    text: fps.toFixed(3).replace(/0+$/, '').replace(/\.$/, ''),
  }));
}
